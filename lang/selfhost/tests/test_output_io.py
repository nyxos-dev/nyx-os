#!/usr/bin/env python3
"""Check N-written driver output progress and failures through the real host shim."""
import argparse
import os
import platform
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile

sys.dont_write_bytecode = True
from test_driver_io import ROOT, SOURCE, TOOLS, require


def output_shim(text):
    anchor = 'static inline nyx_i64 __nyx_syscall6'
    assert text.count(anchor) == 1
    text = text.replace(anchor, '#include <stdlib.h>\nstatic nyx_i64 output_bytes;\n' + anchor)
    anchor = '    if (no == 7) {'
    hook = '''    const char* mode = getenv("NYX_OUTPUT_FAULT");
    if (no == 1 && mode) {
        if (a1 == 2 && mode[0] == 'b') return -5;
        if (a1 == 1) {
            if (mode[0] == 'e' || mode[0] == 'b') return -5;
            if (mode[0] == 'z') return 0;
            if (mode[0] == 'o') return a3 + 1;
            if (mode[0] == 'p' || mode[0] == 'q') {
                if (output_bytes == 7) return mode[0] == 'p' ? -5 : 0;
                if (a3 > 7 - output_bytes) a3 = 7 - output_bytes;
            }
            if (mode[0] == 's' && a3 > 1) a3 = 1;
            if (mode[0] == 't' && a3 > 3) a3 = 3;
            output_bytes += a3;
        }
    }
'''
    assert text.count(anchor) == 1
    return text.replace(anchor, hook + anchor)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--sources', type=Path, default=ROOT/'selfhost')
    args = parser.parse_args()
    if sys.platform != 'linux' or platform.machine().lower() not in ('x86_64', 'amd64'):
        parser.error('requires Linux x86_64 or WSL')
    failures, checks = [], 0
    with tempfile.TemporaryDirectory(prefix='n-output-') as temporary:
        work = Path(temporary)
        require(['gcc', '-std=c99', '-O2', '-Wall', '-Wextra', '-Werror', ROOT/'ncc/ncc.c', '-o', work/'ncc'])
        shutil.copyfile(ROOT.parent/'user/nyxrt.c', work/'nyxrt.c')
        (work/'nyxrt.h').write_text(output_shim((ROOT/'ncc/host/nyxrt.h').read_text()))
        clean = work/'input.n'; clean.write_bytes(SOURCE)
        bad = work/'bad.n'; bad.write_text('fn main() -> i64 { missing_name }\n')
        empty = work/'empty.n'; empty.write_bytes(b'')
        env = dict(os.environ); env.pop('NYX_OUTPUT_FAULT', None)
        def verify(label, result, code, output, error):
            nonlocal checks
            checks += 1
            if (result.returncode, result.stdout, result.stderr) != (code, output, error):
                failures.append(f'{label}: got rc={result.returncode}, out={result.stdout[:80]!r}, err={result.stderr[:80]!r}')
        for tool in TOOLS:
            require([work/'ncc', args.sources.resolve()/f'{tool}.n', '-o', work/f'{tool}.c'])
            if tool != 'check' and args.sources.resolve() == (ROOT/'selfhost').resolve():
                generated = (work/f'{tool}.c').read_bytes().split(b'\n', 1)[1]
                expected_package = f'/* Generated by ncc from {tool}.n */\n'.encode() + generated + (ROOT.parent/'user/nyxrt.c').read_bytes()
                checks += 1
                if (ROOT.parent/f'user/pkg/n{tool}/n{tool}.c').read_bytes() != expected_package:
                    failures.append(f'n{tool}/package: differs from generated C plus the required runtime')
            require(['gcc', '-std=c99', '-pedantic-errors', '-ffreestanding', '-O2', work/f'{tool}.c', work/'nyxrt.c', '-o', work/tool])
            src = bad if tool == 'check' else clean
            normal = subprocess.run([work/tool, src], capture_output=True, env=env, timeout=30)
            assert normal.returncode == (1 if tool == 'check' else 0) and len(normal.stdout) > 7 and not normal.stderr
            for mode in ('', 'short1', 'three'):
                result = subprocess.run([work/tool, src], capture_output=True, env={**env,'NYX_OUTPUT_FAULT':mode}, timeout=30)
                verify(f'{tool}/{mode or "normal"}', result, normal.returncode, normal.stdout, b'')
            message = f'n{tool}: output write failed\n'.encode()
            for mode in ('error', 'zero', 'partial-error', 'quit-after-partial', 'overreport', 'broken-stderr'):
                result = subprocess.run([work/tool, src], capture_output=True, env={**env,'NYX_OUTPUT_FAULT':mode}, timeout=30)
                verify(f'{tool}/{mode}', result, 1, normal.stdout[:7] if mode[0] in 'pq' else b'', b'' if mode[0]=='b' else message)
            with open('/dev/full', 'wb') as sink:
                result = subprocess.run([work/tool, src], stdout=sink, stderr=subprocess.PIPE, env=env, timeout=30)
            result.stdout = b''
            verify(f'{tool}/dev-full', result, 1, b'', message)
            result = subprocess.run([work/tool, src], capture_output=True, env=env, preexec_fn=lambda: os.close(1), timeout=30)
            verify(f'{tool}/closed-stdout', result, 1, b'', message)
            result = subprocess.run([work/tool, empty], capture_output=True, env={**env,'NYX_OUTPUT_FAULT':'error'}, timeout=30)
            verify(f'{tool}/empty-no-output', result, 0, b'', b'')
        result = subprocess.run([work/'check', clean], capture_output=True, env={**env,'NYX_OUTPUT_FAULT':'error'}, timeout=30)
        verify('check/valid-no-output', result, 0, b'', b'')
    for failure in failures:
        print('FAIL', failure)
    print(f'N selfhost output: {checks} checks, {len(failures)} failures')
    return bool(failures)


if __name__ == '__main__':
    raise SystemExit(main())
