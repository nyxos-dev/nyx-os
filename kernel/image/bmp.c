// ============================================================
// bmp.c - a minimal BMP (Windows bitmap) image decoder
// ============================================================
// Handles the uncompressed BITMAPINFOHEADER shapes still seen on the web: 24-bit BGR, 32-bit BGRX,
// and 8-bit palette, stored bottom-up (the default) or top-down (negative height), with each row
// padded to a 4-byte boundary. No RLE compression or BITFIELDS/alpha masks yet (returns an error).
#include "../core/kernel.h"
#include "bmp.h"

#define BMP_MAX_DIM    4096
#define BMP_MAX_PIXELS (1u << 20)

static uint32_t bmp_u32(const uint8_t* p) { return p[0] | ((uint32_t)p[1]<<8) | ((uint32_t)p[2]<<16) | ((uint32_t)p[3]<<24); }
static uint16_t bmp_u16(const uint8_t* p) { return (uint16_t)(p[0] | (p[1]<<8)); }
static int32_t  bmp_s32(const uint8_t* p) { return (int32_t)bmp_u32(p); }

int bmp_decode(const uint8_t* src, uint32_t srclen, image_t* img) {
    if (srclen < 54) return -1;                              // file header (14) + BITMAPINFOHEADER (40)
    if (src[0] != 'B' || src[1] != 'M') return -2;
    uint32_t pixoff  = bmp_u32(src + 10);
    uint32_t hdrsize = bmp_u32(src + 14);
    if (hdrsize < 40) return -3;
    int32_t  w  = bmp_s32(src + 18);
    int32_t  hh = bmp_s32(src + 22);
    uint16_t bpp  = bmp_u16(src + 28);
    uint32_t comp = bmp_u32(src + 30);
    int top_down = hh < 0;
    if (w <= 0 || hh == 0) return -4;
    // Widen before negation: the minimum signed height has no int32_t magnitude.
    uint32_t width = (uint32_t)w;
    uint32_t height = top_down ? (uint32_t)(-(int64_t)hh) : (uint32_t)hh;
    if (comp != 0) return -5;                                // BI_RGB (uncompressed) only
    if (bpp != 24 && bpp != 32 && bpp != 8) return -6;
    if (width > BMP_MAX_DIM || height > BMP_MAX_DIM || (uint64_t)width * height > BMP_MAX_PIXELS) return -7;

    const uint8_t* pal = 0; uint32_t ncol = 0;
    if (bpp == 8) {
        ncol = bmp_u32(src + 46);
        if (ncol == 0) ncol = 256;
        pal = src + 14 + hdrsize;
        if ((uint64_t)14 + hdrsize + (uint64_t)ncol * 4 > srclen) return -8;
    }
    uint32_t stride = ((width * bpp + 31) / 32) * 4;         // rows are padded to 4 bytes
    if ((uint64_t)pixoff + (uint64_t)stride * height > srclen) return -9;

    uint8_t* out = (uint8_t*)kmalloc((uint64_t)width * height * 4);
    if (!out) return -10;
    for (uint32_t y = 0; y < height; y++) {
        uint32_t srcy = top_down ? y : (height - 1 - y);     // BMP is bottom-up unless top-down
        const uint8_t* row = src + pixoff + (uint64_t)srcy * stride;
        uint8_t* orow = out + (uint64_t)y * width * 4;
        for (uint32_t x = 0; x < width; x++) {
            uint8_t* o = orow + x * 4;
            if (bpp == 24)      { const uint8_t* s = row + x*3; o[0]=s[2]; o[1]=s[1]; o[2]=s[0]; o[3]=255; }
            else if (bpp == 32) { const uint8_t* s = row + x*4; o[0]=s[2]; o[1]=s[1]; o[2]=s[0]; o[3]=255; }
            else {                                            // 8-bit palette (BGRX entries)
                uint32_t idx = row[x];
                if (idx < ncol) { o[0]=pal[idx*4+2]; o[1]=pal[idx*4+1]; o[2]=pal[idx*4]; }
                else { o[0]=o[1]=o[2]=0; }
                o[3] = 255;
            }
        }
    }
    img->width = width; img->height = height; img->pixels = out;
    return 0;
}

